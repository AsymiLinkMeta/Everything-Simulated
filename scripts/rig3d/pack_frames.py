"""
Packs the studio renders (render_rig.py --mode frames / overlays) into the AVIF + WebP assets the rig
builder preview shows, and writes the manifest the app reads.

    python3 scripts/rig3d/pack_frames.py /tmp/rig-final

Needs Pillow with AVIF. Output: public/builder-rig/* and src/components/es/rig-photo.ts.
Also checks each overlay against the single "everything" render (render_rig.py --mode full).
"""
import hashlib
import json
import os
import sys

from PIL import Image, ImageChops, ImageStat

SRC = sys.argv[1]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "public", "builder-rig")
MANIFEST = os.path.join(ROOT, "src", "components", "es", "rig-photo.ts")
WIDTH = 900  # the preview is at most 440 CSS px wide on desktop: 900 covers 2x screens
SCREENS = ["s0", "st", "s1", "s2", "s3", "s4"]
FRAMES = [f"{s}m{m}" for s in SCREENS for m in (0, 1)]
OVERLAYS = ["pc", "headset", "headset--raised", "sidemount", "sidemount--raised", "shifter", "shifter--raised", "handbrake", "handbrake--raised"]

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith((".webp", ".avif")):
        os.remove(os.path.join(OUT, f))


def small(img):
    return img if img.width == WIDTH else img.resize((WIDTH, round(img.height * WIDTH / img.width)), Image.LANCZOS)


def write(img, name, ext, **kw):
    tmp = os.path.join(OUT, f"{name}.{ext}")
    img.save(tmp, **kw)
    digest = hashlib.sha1(open(tmp, "rb").read()).hexdigest()[:8]
    final = os.path.join(OUT, f"{name}.{digest}.{ext}")
    os.replace(tmp, final)
    return os.path.basename(final), os.path.getsize(final)


def save(img, name, alpha):
    img = small(img)
    w, ws = write(img, name, "webp", format="WEBP", quality=84 if not alpha else 86, method=6, alpha_quality=90)
    a, as_ = write(img, name, "avif", format="AVIF", quality=62 if not alpha else 70, speed=4)
    return {"webp": w, "avif": a}, {"webp": ws, "avif": as_}


frames, overlays, sizes = {}, {}, {}
for k in FRAMES:
    frames[k], sizes[k] = save(Image.open(os.path.join(SRC, f"frame-{k}.png")).convert("RGB"), f"frame-{k}", False)
for k in OVERLAYS:
    overlays[k], sizes[k] = save(Image.open(os.path.join(SRC, f"overlay-{k}.png")).convert("RGBA"), f"overlay-{k}", True)

# check: s3m1 + every raised overlay against one render of everything (top screen aside)
full_path = os.path.join(SRC, "full-s3m1-all.png")
if os.path.exists(full_path):
    full = Image.open(full_path).convert("RGB")
    comp = Image.open(os.path.join(SRC, "frame-s3m1.png")).convert("RGBA")
    for k in ["pc", "headset--raised", "sidemount--raised", "shifter--raised", "handbrake--raised"]:
        comp.alpha_composite(Image.open(os.path.join(SRC, f"overlay-{k}.png")).convert("RGBA"))
    diff = ImageChops.difference(full, comp.convert("RGB")).convert("L")
    bad = sum(diff.point(lambda v: 1 if v > 40 else 0).histogram()[1:])
    print(f"overlays vs single render: mean diff {ImageStat.Stat(diff).mean[0]:.2f}/255, pixels off by >40: {bad} of {diff.width * diff.height}")
    comp.convert("RGB").save(os.path.join(SRC, "composite.png"))

kb = lambda d, f: d[f] / 1024
print(f"frames (avif): {', '.join(f'{k} {kb(sizes[k], 'avif'):.0f}' for k in FRAMES)} KB")
print(f"frames (webp): {', '.join(f'{k} {kb(sizes[k], 'webp'):.0f}' for k in FRAMES)} KB")
print(f"overlays (avif): {', '.join(f'{k} {kb(sizes[k], 'avif'):.0f}' for k in OVERLAYS)} KB")
print(f"empty view (s3m0): avif {kb(sizes['s3m0'], 'avif'):.0f} KB, webp {kb(sizes['s3m0'], 'webp'):.0f} KB")
h = round(Image.open(os.path.join(SRC, "frame-s3m0.png")).height * WIDTH / Image.open(os.path.join(SRC, "frame-s3m0.png")).width)
ts = f"""// Generated by scripts/rig3d/pack_frames.py from the Blender renders. Do not edit by hand.
export type RigPhotoFile = {{ avif: string; webp: string }};
/** Full-frame studio photos, one per screen layout (s0 none, st stand, s1-s3 screens, s4 triple + top) and motion (m1). */
export const RIG_PHOTO_FRAMES: Record<string, RigPhotoFile> = {json.dumps(frames, indent=2, sort_keys=True)};
/** Add-on layers drawn over the photo ("--raised" for a motion build). */
export const RIG_PHOTO_OVERLAYS: Record<string, RigPhotoFile> = {json.dumps(overlays, indent=2, sort_keys=True)};
export const RIG_PHOTO_SIZE = {{ width: {WIDTH}, height: {h} }};
export const RIG_PHOTO_BASE = "/builder-rig/";
"""
open(MANIFEST, "w").write(ts)
print("wrote", MANIFEST)
