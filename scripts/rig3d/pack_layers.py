"""
Packs the Blender layer renders (render_rig.py --mode full / layers) into the WebP assets the
rig builder preview stacks, writes the manifest the app reads, and checks that the stacked
layers reproduce the single full render.

    python3 scripts/rig3d/pack_layers.py /tmp/rig-final

Needs Pillow. Output: public/builder-rig/*.webp and src/components/es/rig-photo.ts.
"""
import hashlib
import json
import os
import sys

from PIL import Image, ImageChops, ImageStat

SRC = sys.argv[1]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "public", "builder-rig")
MANIFEST = os.path.join(ROOT, "src", "components", "es", "rig-photo.ts")
WIDTH = 900  # the preview is at most 380 CSS px wide on desktop: 900 covers 2x screens

# Back-to-front order from scripts/rig3d/stack_order.py (ground and raised agree).
ORDER = [
    "motion", "mount", "chassis-back", "mount-sides", "mount-top", "pc", "pedals", "chassis",
    "screen-center", "screen-sides", "screen-dual", "screen-top", "seat", "sidemount", "shifter",
    "handbrake", "wheelbase", "wheel", "headset",
]
RAISED = {"chassis-back", "chassis", "seat", "wheelbase", "wheel", "pedals", "sidemount", "shifter", "handbrake", "headset"}
SHADOWS = ["shadow-rig", "shadow-rig--raised", "shadow-stand", "shadow-pc"]
# What an empty build shows (rigPartStates with nothing picked): everything as a ghost except
# the top screen and its frame extension, the dual screens and the raised frame.
EMPTY = [n for n in ORDER if n not in ("motion", "mount-top", "screen-top", "screen-dual")]

os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith(".webp"):
        os.remove(os.path.join(OUT, f))


def load(name):
    return Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")


def save(img, name, quality):
    small = img.resize((WIDTH, round(img.height * WIDTH / img.width)), Image.LANCZOS)
    tmp = os.path.join(OUT, name + ".webp")
    small.save(tmp, "WEBP", quality=quality, method=6, alpha_quality=90)
    digest = hashlib.sha1(open(tmp, "rb").read()).hexdigest()[:8]
    final = os.path.join(OUT, f"{name}.{digest}.webp")
    os.replace(tmp, final)
    return os.path.basename(final), os.path.getsize(final)


files, sizes = {}, {}
for n in ORDER:
    files[n], sizes[n] = save(load(n), n, 84)
    if n in RAISED:
        files[n + "--raised"], sizes[n + "--raised"] = save(load(n + "--raised"), n + "--raised", 84)
for n in SHADOWS:
    files[n], sizes[n] = save(load(n), n, 70)

# ghosted empty state: the default rig flattened, desaturated and faint, in one small file
base = load(EMPTY[0])
canvas = Image.new("RGBA", base.size, (0, 0, 0, 0))
for n in EMPTY:
    canvas.alpha_composite(load(n))
grey = canvas.convert("LA").convert("RGBA")
r, g, b, a = grey.split()
lift = r.point(lambda v: min(255, int(70 + v * 1.6)))
alpha = a.point(lambda v: int(v * 0.2))
ghost = Image.merge("RGBA", (lift, lift, lift, alpha))
files["ghost-empty"], sizes["ghost-empty"] = save(ghost, "ghost-empty", 60)

# check: the stacked layers of a fully loaded, raised rig against the single full render
full = load("full")
stack = Image.new("RGBA", full.size, (0, 0, 0, 0))
for n in ORDER:
    if n == "screen-dual":
        continue
    stack.alpha_composite(load(n + "--raised" if n in RAISED else n))
bg = Image.new("RGBA", full.size, (10, 10, 13, 255))
a_img = bg.copy(); a_img.alpha_composite(full)
b_img = bg.copy(); b_img.alpha_composite(stack)
diff = ImageChops.difference(a_img.convert("RGB"), b_img.convert("RGB")).convert("L")
mean = ImageStat.Stat(diff).mean[0]
bad = sum(1 for v in diff.getdata() if v > 40)
print(f"composite vs full: mean diff {mean:.2f}/255, pixels off by >40: {bad} of {diff.width * diff.height}")
diff.point(lambda v: min(255, v * 4)).save(os.path.join(SRC, "composite-diff.png"))
b_img.convert("RGB").save(os.path.join(SRC, "composite.png"))
a_img.convert("RGB").save(os.path.join(SRC, "full-on-bg.png"))

empty_kb = (sizes["ghost-empty"] + sizes["shadow-rig"] + sizes["shadow-stand"] + sizes["shadow-pc"]) / 1024
all_kb = sum(sizes.values()) / 1024
print(f"empty view: {empty_kb:.0f} KB; all {len(files)} files: {all_kb:.0f} KB")
for n in sorted(sizes, key=lambda k: -sizes[k])[:6]:
    print(f"  {n}: {sizes[n] / 1024:.0f} KB")

ts = f"""// Generated by scripts/rig3d/pack_layers.py from the Blender renders. Do not edit by hand.
/** Pre-rendered rig layers, back to front (see scripts/rig3d/stack_order.py). */
export const RIG_PHOTO_ORDER = {json.dumps(ORDER)} as const;
/** Layers that sit on the frame and have a raised (motion platform) render. */
export const RIG_PHOTO_RAISED: readonly string[] = {json.dumps(sorted(RAISED))};
export const RIG_PHOTO_SIZE = {{ width: {WIDTH}, height: {round(full.height * WIDTH / full.width)} }};
export const RIG_PHOTO_BASE = "/builder-rig/";
export const RIG_PHOTO_FILES: Record<string, string> = {json.dumps(files, indent=2, sort_keys=True)};
"""
open(MANIFEST, "w").write(ts)
print("wrote", MANIFEST)
